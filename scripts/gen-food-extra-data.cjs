function pickFoods(items, n) {
  const names = items.map(f => f.name);
  if (names.length <= n) return names;
  const result = [];
  const step = Math.floor(names.length / n);
  for (let i = 0; i < n; i++) result.push(names[Math.min(i * step, names.length - 1)]);
  return result;
}

